// Helper: get stream by id
export const getStream = (id: string) => STREAMS.find(s => s.id === id)

// Helper: get field label
export const getFieldLabel = (streamId: string, fieldId: string) => {
  const stream = getStream(streamId)
  return stream?.fields.find(f => f.id === fieldId)?.label || fieldId
}

// All stream IDs for quick reference
export const STREAM_IDS = STREAMS.map(s => s.id)
